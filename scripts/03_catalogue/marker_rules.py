def annotate(genes):
    g = set(x.strip() for x in genes.split(","))
    hits = [(lbl, len(g & mk)) for lbl, mk, need in RULES if len(g & mk) >= need]
    if not hits:
        return "", ""
    hits.sort(key=lambda h: -h[1])
    ev = ", ".join(sorted(g & dict((l, m) for l, m, _ in RULES)[hits[0][0]]))
    return hits[0][0], ev
